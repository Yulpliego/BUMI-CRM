using Microsoft.EntityFrameworkCore;

namespace NexoCrm;

internal static class ImprovementSchema
{
    public static Task Apply(CrmDb db) => db.Database.ExecuteSqlRawAsync("""
        CREATE TABLE IF NOT EXISTS "CampaignOrigins" (
            "CampaignId" integer REFERENCES "Campaigns" ("Id"), "PartyId" integer REFERENCES "Parties" ("Id"),
            "CapturedOn" date NOT NULL, "Source" text NOT NULL, "Segment" text NOT NULL, "Cost" numeric NOT NULL,
            PRIMARY KEY ("CampaignId", "PartyId"), UNIQUE ("PartyId"));
        CREATE TABLE IF NOT EXISTS "QuoteVersions" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "QuoteId" integer NOT NULL REFERENCES "Quotes" ("Id"),
            "Revision" uuid NOT NULL, "At" timestamptz NOT NULL, "Actor" text NOT NULL, "Snapshot" text NOT NULL,
            "Total" numeric NOT NULL, "MaxDiscount" numeric NOT NULL, "Approval" text NOT NULL,
            "DecisionBy" text NOT NULL, "DecisionReason" text NOT NULL, "DecidedAt" timestamptz,
            UNIQUE ("QuoteId", "Revision"));
        CREATE TABLE IF NOT EXISTS "Fulfillments" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "SaleId" integer NOT NULL REFERENCES "Sales" ("Id"),
            "Position" integer NOT NULL, "Quantity" integer NOT NULL, "Kind" text NOT NULL, "Reason" text NOT NULL,
            "EffectiveOn" date NOT NULL, "PromisedOn" date, "Actor" text NOT NULL, "RequestId" uuid NOT NULL,
            UNIQUE ("SaleId", "RequestId"));
        CREATE TABLE IF NOT EXISTS "SupplyTerms" (
            "SupplierId" integer REFERENCES "Suppliers" ("Id"), "ProductId" integer REFERENCES "Products" ("Id"),
            "Cost" numeric NOT NULL, "LeadDays" integer NOT NULL, PRIMARY KEY ("SupplierId", "ProductId"));
        CREATE TABLE IF NOT EXISTS "PurchaseDrafts" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "SupplierId" integer NOT NULL REFERENCES "Suppliers" ("Id"),
            "ProductId" integer NOT NULL REFERENCES "Products" ("Id"), "Quantity" integer NOT NULL,
            "UnitCost" numeric NOT NULL, "Due" date NOT NULL, "Received" date, "Status" text NOT NULL, "Actor" text NOT NULL);
        CREATE TABLE IF NOT EXISTS "AgendaChanges" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "AgendaId" integer NOT NULL REFERENCES "AgendaItems" ("Id"),
            "OwnerId" integer NOT NULL REFERENCES "Accounts" ("Id"), "Due" timestamptz NOT NULL, "At" timestamptz NOT NULL,
            "NewDue" timestamptz, "Kind" text NOT NULL, "Reason" text NOT NULL, "Actor" text NOT NULL);
        CREATE TABLE IF NOT EXISTS "NoticePreferences" (
            "AccountId" integer PRIMARY KEY REFERENCES "Accounts" ("Id"), "QuietFrom" integer NOT NULL,
            "QuietUntil" integer NOT NULL, "EscalationHours" integer NOT NULL, "Priority" text NOT NULL);
        CREATE TABLE IF NOT EXISTS "AccountSessions" (
            "Id" uuid PRIMARY KEY, "AccountId" integer NOT NULL REFERENCES "Accounts" ("Id"), "Version" uuid NOT NULL,
            "Started" timestamptz NOT NULL, "Expires" timestamptz NOT NULL, "Device" text NOT NULL, "Revoked" boolean NOT NULL);
        CREATE TABLE IF NOT EXISTS "BumiPasskeys" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "AccountId" integer NOT NULL REFERENCES "Accounts" ("Id"),
            "Credential" bytea NOT NULL UNIQUE, "Data" text NOT NULL, "Name" text NOT NULL, "Added" timestamptz NOT NULL);
        CREATE TABLE IF NOT EXISTS "PasskeyFlows" (
            "Id" uuid PRIMARY KEY, "AccountId" integer NOT NULL REFERENCES "Accounts" ("Id"), "Version" uuid NOT NULL,
            "Kind" text NOT NULL, "State" text NOT NULL, "Expires" timestamptz NOT NULL);
        ALTER TABLE "NoticeReceipts" ADD COLUMN IF NOT EXISTS "Group" text NOT NULL DEFAULT '';
        ALTER TABLE "NoticeReceipts" ADD COLUMN IF NOT EXISTS "AcknowledgementSeconds" integer;
        CREATE INDEX IF NOT EXISTS "IX_PurchaseDrafts_ProductId" ON "PurchaseDrafts" ("ProductId");
        CREATE INDEX IF NOT EXISTS "IX_AgendaChanges_OwnerId_At" ON "AgendaChanges" ("OwnerId","At");
        CREATE INDEX IF NOT EXISTS "IX_AccountSessions_AccountId" ON "AccountSessions" ("AccountId");
        """);
}
